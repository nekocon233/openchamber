import path from 'node:path';

// The gateway's config file is generated from the store before every spawn and
// never read back: the process rewrites it at startup (it hashes the plaintext
// management key) and its management API normalizes the whole file on write.
// Hand edits are overwritten by design; the header says so.
const quote = (value) => JSON.stringify(value);

export const gatewayConfigPath = (dataDir) => path.join(dataDir, 'native-agents', 'cliproxyapi', 'config.yaml');

/**
 * `JSON.stringify` produces scalars that are also valid double-quoted YAML and
 * that escape Windows path separators correctly.
 */
export const renderGatewayConfig = ({ port, authDir, upstreamProxy, managementKey, clientKeys }) => {
  const lines = [
    '# Generated by OpenChamber from native-agents/cliproxyapi.json.',
    '# Every field is rewritten before the gateway starts; edits here are lost.',
    'config-version: 8',
    'server:',
    '    host: "127.0.0.1"',
    `    port: ${port}`,
    'management:',
    '    allow-remote: false',
    `    secret-key: ${quote(managementKey)}`,
    '    disable-control-panel: true',
    'access:',
    '    api-keys:',
    ...clientKeys.map((key) => `        - ${quote(key)}`),
    'routing:',
    '    strategy: "round-robin"',
    '    session-affinity: true',
    'oauth:',
    `    auth-dir: ${quote(authDir)}`,
  ];
  if (upstreamProxy !== null) {
    lines.push('requests:', `    proxy-url: ${quote(upstreamProxy)}`);
  }
  return `${lines.join('\n')}\n`;
};

// Go ignores the macOS system proxy, so the config field is the only visible
// source of proxy truth. A stray shell proxy would silently override the value
// the user just set, so it is stripped, and loopback stays direct.
const PROXY_VARIABLES = [
  'HTTP_PROXY', 'HTTPS_PROXY', 'ALL_PROXY', 'NO_PROXY',
  'http_proxy', 'https_proxy', 'all_proxy', 'no_proxy',
];

export const gatewayChildEnv = (baseEnv) => {
  const env = { ...baseEnv };
  for (const name of PROXY_VARIABLES) delete env[name];
  env.NO_PROXY = '127.0.0.1,localhost,::1';
  env.no_proxy = env.NO_PROXY;
  return env;
};
