import { describe, expect, it } from 'vitest';
import { gatewayChildEnv, renderGatewayConfig } from './config.js';

const input = {
  port: 8317,
  authDir: '/Users/test/.cli-proxy-api',
  upstreamProxy: null,
  managementKey: 'management-key',
  clientKeys: ['client-key'],
};

describe('CLIProxyAPI generated config', () => {
  it('renders the managed shape the gateway reads at startup', () => {
    expect(renderGatewayConfig(input)).toBe(`# Generated by OpenChamber from native-agents/cliproxyapi.json.
# Every field is rewritten before the gateway starts; edits here are lost.
config-version: 8
server:
    host: "127.0.0.1"
    port: 8317
management:
    allow-remote: false
    secret-key: "management-key"
    disable-control-panel: true
access:
    api-keys:
        - "client-key"
routing:
    strategy: "round-robin"
    session-affinity: true
oauth:
    auth-dir: "/Users/test/.cli-proxy-api"
`);
  });

  it('adds the upstream proxy only when one is set', () => {
    const withProxy = renderGatewayConfig({ ...input, upstreamProxy: 'http://127.0.0.1:7890' });
    expect(withProxy).toContain('requests:\n    proxy-url: "http://127.0.0.1:7890"\n');
    expect(renderGatewayConfig(input)).not.toContain('requests:');
  });

  it('keeps Windows paths intact and lists every client key', () => {
    const rendered = renderGatewayConfig({ ...input, authDir: 'C:\\Users\\test\\.cli-proxy-api', clientKeys: ['one', 'two'] });
    expect(rendered).toContain('auth-dir: "C:\\\\Users\\\\test\\\\.cli-proxy-api"');
    expect(rendered).toContain('        - "one"\n        - "two"\n');
  });

  it('makes the config file the only proxy the child can see', () => {
    const env = gatewayChildEnv({ PATH: '/usr/bin', HTTPS_PROXY: 'http://elsewhere:1', http_proxy: 'http://elsewhere:1', HOME: '/Users/test' });
    expect(env).toEqual({ PATH: '/usr/bin', HOME: '/Users/test', NO_PROXY: '127.0.0.1,localhost,::1', no_proxy: '127.0.0.1,localhost,::1' });
  });
});
